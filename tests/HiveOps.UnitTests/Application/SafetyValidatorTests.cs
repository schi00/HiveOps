using FluentAssertions;
using HiveOps.Application;
using Xunit;

namespace HiveOps.UnitTests.Application;

public sealed class SafetyValidatorTests
{
    [Theory]
    // Single statements — allowed
    [InlineData("SELECT * FROM Users", true)]
    [InlineData("SELECT TOP 50 * FROM Incidents ORDER BY CreatedAt DESC", true)]
    [InlineData("SELECT COUNT(*) FROM Conversations", true)]
    [InlineData("INSERT INTO AuditLog (Message) VALUES ('fixed')", true)]
    [InlineData("INSERT INTO AuditLog (Message) VALUES ('a;b')", true)] // ';' inside literal
    [InlineData("UPDATE Users SET Name = 'x' WHERE Id = 1", true)]
    [InlineData("UPDATE Users SET Name = 'x' WHERE Id = 1;", true)]
    [InlineData("UPDATE Users SET Name = 'x' WHERE Email LIKE '%@hive.com'", true)]
    [InlineData("DELETE FROM Users WHERE Id = 5", true)]
    [InlineData("DELETE FROM Users WHERE Id IN (1, 2, 3)", true)]
    // Single statements — rejected
    [InlineData("UPDATE Users SET Name = 'x'", false)]
    [InlineData("UPDATE Users SET Name = 'x' WHERE 1 = 1", false)]
    [InlineData("UPDATE Users SET Name = 'x' WHERE Id = 1 OR 1=1", false)]
    [InlineData("UPDATE Users SET Name = 'x' WHERE TRUE", false)]
    [InlineData("DELETE FROM Users", false)]
    [InlineData("DELETE FROM Users WHERE 'a' = 'a'", false)]
    [InlineData("SELECT * FROM A UNION SELECT * FROM B", false)]
    [InlineData("SELECT * FROM A UNION ALL SELECT * FROM B", false)]
    [InlineData("EXEC xp_cmdshell 'dir'", false)]
    [InlineData("EXEC sp_configure 'show advanced options', 1", false)]
    [InlineData("EXECUTE('SELECT 1')", false)]
    [InlineData("DROP TABLE Users", false)]
    [InlineData("TRUNCATE TABLE Users", false)]
    [InlineData("ALTER TABLE Users DROP COLUMN Name", false)]
    [InlineData("BULK INSERT Users FROM 'c:\\data.csv'", false)]
    [InlineData("GRANT SELECT ON Users TO app", false)]
    // Multi-statement scripts — dangerous statement anywhere must fail
    [InlineData("UPDATE Users SET Name = 'x' WHERE Id = 1; DROP TABLE Users", false)]
    [InlineData("SELECT * FROM A; UPDATE B SET Y = 1", false)]
    [InlineData("SELECT * FROM A; SELECT * FROM B; EXEC xp_cmdshell 'dir'", false)]
    [InlineData("SELECT 1; -- done", true)]
    [InlineData("UPDATE A SET X = 1 WHERE Id = 1; UPDATE B SET Y = 2 WHERE Id = 2", true)]
    public void IsSafeSql_ReturnsExpectedResult(string sql, bool expected)
    {
        SafetyValidator.IsSafeSql(sql).Should().Be(expected);
    }

    [Fact]
    public void IsSafeSql_Multi_statement_script_with_comments_is_allowed()
    {
        var script = """
            -- Fix step 1: reset stale rows
            UPDATE Incidents
            SET Status = 'Open'
            WHERE Id = 'a1b2';

            /* step 2: audit trail */
            INSERT INTO AuditLog (Message) VALUES ('fix applied');
            """;

        SafetyValidator.IsSafeSql(script).Should().BeTrue();
    }

    [Fact]
    public void IsSafeSql_Worker_generated_fix_with_comment_and_multiline_where_is_allowed()
    {
        // Mirrors the rule-based fix generated by IncidentAutoWorkflowService
        var script = """
            -- Fix for invalid JSON payloads
            UPDATE DiagnosticLogs 
            SET RawPayload = REPLACE(RawPayload, ',,', ','),
                UpdatedAt = SYSDATETIMEOFFSET()
            WHERE RawPayload LIKE '%[%,,%';
            """;

        SafetyValidator.IsSafeSql(script).Should().BeTrue();
    }

    [Fact]
    public void IsSafeSql_Multi_statement_with_one_bad_statement_is_rejected()
    {
        var script = """
            UPDATE A SET X = 1 WHERE Id = 1;
            SELECT * FROM B;
            DELETE FROM C;
            """;

        SafetyValidator.IsSafeSql(script).Should().BeFalse();
        SafetyValidator.GetRejectionReason(script)
            .Should().Contain("Statement 3").And.Contain("DELETE");
    }

    [Theory]
    [InlineData("UPDATE Users SET Name = 'x' WHERE Id = 1", true)]
    [InlineData("DELETE FROM Users WHERE Id = 'abc-123'", true)]
    [InlineData("UPDATE Users SET Name = 'x' WHERE Email = 'a@b.com'", false)]
    [InlineData("UPDATE Users SET Name = 'x' -- WHERE Id = 1", false)] // commented WHERE does not count
    public void HasPrimaryKeyWhere_ReturnsExpectedResult(string sql, bool expected)
    {
        SafetyValidator.HasPrimaryKeyWhere(sql).Should().Be(expected);
    }

    [Theory]
    [InlineData("")]
    [InlineData("   ")]
    [InlineData("DELETE FROM Users")]
    [InlineData("-- only a comment")]
    public void GetRejectionReason_ForUnsafeSql_ReturnsMessage(string sql)
    {
        SafetyValidator.GetRejectionReason(sql).Should().NotBeNullOrWhiteSpace();
        SafetyValidator.IsSafeSql(sql).Should().BeFalse();
    }

    [Theory]
    [InlineData("SELECT * FROM Users")]
    [InlineData("UPDATE Users SET Name = 'x' WHERE Id = 1")]
    [InlineData("UPDATE A SET X = 1 WHERE Id = 1; DELETE FROM B WHERE Id = 2")]
    public void GetRejectionReason_ForSafeSql_ReturnsNull(string sql)
    {
        SafetyValidator.GetRejectionReason(sql).Should().BeNull();
    }

    [Theory]
    // Sensitive tables blocked regardless of query shape
    [InlineData("SELECT * FROM credentials", "credentials")]
    [InlineData("SELECT * FROM user_credentials WHERE user_id = 1", "user_credentials")]
    [InlineData("SELECT hash FROM passwords LIMIT 5", "passwords")]
    [InlineData("SELECT * FROM api_keys", "api_keys")]
    [InlineData("SELECT * FROM refresh_tokens WHERE user_id = 7", "refresh_tokens")]
    [InlineData("SELECT * FROM sessions WHERE active = true", "sessions")]
    [InlineData("SELECT * FROM oauth_clients", "oauth_clients")]
    [InlineData("SELECT * FROM private_keys", "private_keys")]
    [InlineData("SELECT u.email FROM users u JOIN credentials c ON c.user_id = u.id", "credentials")]
    // Schema-qualified references resolve to the table part
    [InlineData("SELECT * FROM auth.sessions", "sessions")]
    [InlineData("SELECT * FROM \"public\".\"tokens\"", "tokens")]
    public void FindBlockedTableReference_SensitiveTable_ReturnsName(string sql, string expectedTable)
    {
        SafetyValidator.FindBlockedTableReference(sql).Should().Be(expectedTable);
    }

    [Theory]
    // Normal business tables are never blocked
    [InlineData("SELECT * FROM Users")]
    [InlineData("SELECT * FROM incidents WHERE status = 'open'")]
    [InlineData("SELECT o.id FROM orders o JOIN order_items i ON i.order_id = o.id")]
    [InlineData("SELECT COUNT(*) FROM conversations")]
    // 'token' inside a word does not match (word-boundary anchored)
    [InlineData("SELECT * FROM tokenized_products")]
    public void FindBlockedTableReference_NormalTable_ReturnsNull(string sql)
    {
        SafetyValidator.FindBlockedTableReference(sql).Should().BeNull();
    }

    [Fact]
    public void FindBlockedTableReference_TenantExtraPattern_BlocksTable()
    {
        var blocked = new[] { "^legacy_users$", "hr_" };
        SafetyValidator.FindBlockedTableReference("SELECT * FROM legacy_users", blocked).Should().Be("legacy_users");
        SafetyValidator.FindBlockedTableReference("SELECT * FROM hr_payroll", blocked).Should().Be("hr_payroll");
        SafetyValidator.FindBlockedTableReference("SELECT * FROM incidents", blocked).Should().BeNull();
    }

    [Fact]
    public void FindBlockedTableReference_CommentHiddenTable_IsStillDetected()
    {
        // Comments are stripped before scanning, so they cannot smuggle a table reference
        SafetyValidator.FindBlockedTableReference(
            "SELECT * /* innocuous */ FROM credentials").Should().Be("credentials");
    }
}
